/**
 * Traduz o nome de um equipamento
 */
export function translateEquipmentName(name: string, locale: string): string {
  const translations = EQUIPMENT_TRANSLATIONS[locale as keyof typeof EQUIPMENT_TRANSLATIONS];
  if (!translations) return name;
  
  return translations[name as keyof typeof translations] || name;
}

/**
 * Traduz o nome de uma categoria de equipamento
 */
export function translateEquipmentCategory(category: string, locale: string): string {
  const { translateDnd5eTerm } = require("./dnd5e-translations");
  return translateDnd5eTerm(category, locale);
}

