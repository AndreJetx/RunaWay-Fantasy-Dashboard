/**
 * Traduz o nome de uma magia
 */
export function translateSpellName(name: string, locale: string): string {
  const translations = SPELL_TRANSLATIONS[locale as keyof typeof SPELL_TRANSLATIONS];
  if (!translations) return name;
  
  return translations[name as keyof typeof translations] || name;
}

